    static func hash(_ text: String) -> String {
        SHA256.hash(data: Data(text.precomposedStringWithCanonicalMapping.lowercased().utf8)).map { String(format: "%02x", $0) }.joined()
    }

    /// Each run of letters, and its parts where a capital follows a small letter (`ScanName`).
    static func words(_ text: String) -> [String] {
        var out: [String] = [], run = "", part = ""
        func close() {
            if !run.isEmpty { out.append(run) }
            if !part.isEmpty, part != run { out.append(part) }
            run = ""; part = ""
        }
        for ch in text.precomposedStringWithCanonicalMapping {
            guard ch.isLetter else { close(); continue }
            if ch.isUppercase, let last = part.last, last.isLowercase { out.append(part); part = "" }
            run.append(ch); part.append(ch)
        }
        close()
        return out
    }

    /// Dates as a birth date is written (`dd.mm.yy`, `dd/mm/yyyy`, `yyyy-mm-dd`, `d May yyyy`) and
    /// phone numbers, as their digits alone.
    static func datesAndNumbers(_ text: String) -> [String] {
        let dates = text.matches(of: /\d{1,2}[.\/]\d{1,2}[.\/]\d{2,4}|\d{4}-\d{2}-\d{2}|\d{1,2}\.? (?:May|Mai) \d{4}/).map { String($0.output) }
        let numbers = text.matches(of: /\+?\d[\d \/-]{6,}\d/).map { String($0.output).filter(\.isNumber) }
        return dates + numbers
    }

    @Test("F024 AC-2 · no old name, birth date or number is left in a test file")
    func noOldDetailLeft() throws {
        var left: [String] = []
        for folder in Self.folders {
            let files = FileManager.default.enumerator(at: folder, includingPropertiesForKeys: nil)
            while let url = files?.nextObject() as? URL {
                // F024 AC-3's golden file is what the hiding writes from these cases: its other words are the
                // stand-ins of `Pool`, which the code makes, not people of the cases.
                if url.lastPathComponent == "f024-golden.json" { continue }
                guard let text = try? String(contentsOf: url, encoding: .utf8) else { continue }
                let found = Set((Self.words(text) + Self.datesAndNumbers(text)).filter { Self.old.contains(Self.hash($0)) })
                if !found.isEmpty { left.append("\(url.lastPathComponent): \(found.count)") }
            }
        }
        #expect(left.isEmpty, "old details left in: \(left.sorted())")
    }
